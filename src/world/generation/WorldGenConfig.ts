// --- Размеры секций ---

// Первая секция — узкий «входной шлюз» для мягкого онбординга.
export const FIRST_SECTION_WIDTH = 8;
// Остальные секции — ровно в 3 раза шире.
export const SECTION_WIDTH = FIRST_SECTION_WIDTH * 3;
export const FIRST_SECTION_LENGTH = { min: 12, max: 18 };
export const SECTION_LENGTH = { min: 36, max: 54 }; // 12-18 × 3

// --- Изгиб трассы ---

/**
 * Максимальный изгиб на стыке секций в рад (~29°): весь коридор явно
 * «гуляет», а не идёт почти по прямой с редкими лёгкими подворотами.
 */
export const MAX_BEND = 0.5;
/** Потолок накопленного изгиба трассы (~80°), чтобы коридор не закручивался в спираль. */
export const MAX_YAW = 1.4;

// --- Развилки / тупики ---

/** Вероятность, что секция закончится развилкой (двумя воротами). */
export const FORK_PROBABILITY = 0.45;
/**
 * Вероятность тупика — второй, независимой развилки-варианта, проверяется,
 * только если «настоящая» развилка НЕ выпала: итоговый шанс скрестить какую-либо
 * из двух дверей = FORK_PROBABILITY + DEADEND_PROBABILITY. Тупик выглядит снаружи
 * как обычная развилка (те же двойные ворота), но одна из двух дверей ведёт в
 * короткий рукав без выхода — барьер не запирается за спиной.
 */
export const DEADEND_PROBABILITY = 0.2;
/** Доля ширины коридора, которую закрывает один барьер при развилке. */
export const FORK_GATE_FRACTION = 0.5;
/** Длина параллельных коридоров-веток за развилкой (до схождения в общую секцию). */
export const FORK_BRANCH_LENGTH = { min: 22, max: 38 };
/**
 * Суммарный угол расхождения ветки развилки (рад) от исходного курса. Величина
 * случайна на каждую развилку, знак — зеркально противоположный у двух веток.
 * Верхняя граница подобрана так, чтобы даже на самой длинной ветке боковой снос
 * к месту стыка с J оставался заметно меньше off (=SECTION_WIDTH/4).
 */
export const FORK_DIVERGENCE_ANGLE = { min: 0.12, max: 0.26 };
/** Длина тупикового рукава — заметно короче настоящей ветки: бонусный уголок, не часть пути. */
export const DEADEND_LENGTH = { min: 12, max: 24 };

// --- Боковые ниши (перпендикулярные тупики через проём в стене) ---

/**
 * Шанс ниши на каждую полноширинную стволовую секцию (обычную ИЛИ схождение J —
 * не на первую и не на подход). Ветки развилки и её тупик сюда не входят.
 */
export const SIDE_SPUR_PROBABILITY = 0.35;
/** Ширина ниши = ширина проёма в стене родителя. */
export const SIDE_SPUR_WIDTH = 6;
/** Длина рукава ниши — короче даже тупика развилки: карман на пару шагов. */
export const SIDE_SPUR_LENGTH = { min: 7, max: 13 };
/** Отступ от концов секции (вход/выход/ворота), внутри которого проём не ставим. */
export const SIDE_SPUR_MARGIN = 9;

