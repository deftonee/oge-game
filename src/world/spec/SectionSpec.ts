/**
 * Модель данных секции мира (сериализуемый «spec», а не объекты сцены).
 *
 * Это НЕ геометрия и НЕ логика — только описание: где секция, какой она формы
 * (start/yaw/curvature/length), какие на ней объекты и как они связаны
 * (fork/join/гейты). Потребители: генератор (создаёт), SectionChunk (материализует
 * геометрию), WorldStreamer (стриминг), FogManager (туман), SectionContent (контент).
 */

import type { Vec2 } from "../geometry/SectionGeometry";
import type { BiomeId } from "../biomes/biomeIds";

export interface WitchSpec {
  id: string;
  /** Локальная координата поперёк коридора. */
  x: number;
  /** Локальная координата вдоль коридора (0 = вход секции). */
  z: number;
  spellId: string;
}

export interface BonfireSpec {
  id: string;
  x: number;
  z: number;
}

export interface ScatterSeed {
  x: number;
  z: number;
  rot: number;
  scale: number;
}

export type PracticeTargetKind = "tree" | "dummy" | "nettle";

export interface PracticeTargetSpec {
  id: string;
  x: number;
  z: number;
  kind: PracticeTargetKind;
}

/**
 * Сундук в секции (локальные координаты). Содержимое — книги (ветки прокачки)
 * и страницы (заклинания) двух видов:
 *   - рукописное: точные `bookIds`/`pageIds` (вводные и сюжетные сундуки);
 *   - динамическое: заданы только `dynamic.slots` (число предметов), а что
 *     именно внутри, решается при открытии из состояния игрока
 *     (см. learning/chestLoot.ts) — мир целиком генерируется на старте, когда
 *     игрок ещё ничего не нашёл. У динамических `bookIds`/`pageIds` пусты.
 */
export interface ChestSpec {
  id: string;
  x: number;
  z: number;
  bookIds: string[];
  pageIds: string[];
  dynamic?: { slots: number };
}

/**
 * Перпендикулярный боковой тупик («ниша»): короткий САМОСТОЯТЕЛЬНЫЙ рукав,
 * отходящий от основного коридора ПОД УГЛОМ 90° через проём в его стене.
 * У неё собственные пол/стены/торцевая стена в собственной локальной системе
 * координат (`start`/`yaw`, curvature всегда 0 — рукав короткий и прямой),
 * связанные с родителем только проёмом в его стене (проём получается сам:
 * пол рукава заходит в пол родителя, см. geometry/Footprint). Всегда ровно один сундук и одна охраняющая его
 * ведьма (см. SectionContentBuilder.buildSideSpurContent).
 */
export interface SideSpurSpec {
  id: string;
  /** К какой стене родителя пристроена ниша — нужно для выреза проёма. */
  side: "left" | "right";
  /** Мировая точка проёма (локальный (0,0) ниши). */
  start: Vec2;
  /** Курс рукава в мире — перпендикулярен родителю в точке проёма. */
  yaw: number;
  /** Ширина ниши (она же ширина проёма в стене родителя). */
  width: number;
  /** Длина рукава от проёма до тупиковой торцевой стены. */
  length: number;
  /** Локальная (вдоль оси РОДИТЕЛЯ) позиция проёма — для выреза в его стене. */
  doorZ: number;
  /** Координаты — локальные координаты НИШИ (0,0 = проём). */
  witch: WitchSpec;
  chest: ChestSpec;
}

/**
 * Выходные ворота секции (стоят на её КОНЦЕ). У секции их 0..2:
 *   0 — только у служебной секции подхода к башне (дальше туман и башня),
 *   1 — обычный проход в следующую секцию,
 *   2 — развилка: два барьера по половине коридора на разные ветки прокачки.
 */
export interface GateSpec {
  id: string;
  /** Сколько тем нужно изучить суммарно (по любой школе), чтобы пробить барьер. */
  requiredSpells: number;
  /** Ветка прокачки (школа), к которой ведут ворота — тематика барьера. */
  schoolId: string | null;
  /** Локальный x центра барьера (0 — одиночные ворота; у развилки — центр своей ветки). */
  x: number;
  /** Ширина барьера. */
  width: number;
  /** Ворота развилки: после открытия проход только вперёд (односторонний блок). */
  fork?: boolean;
}

export type BorderStyle = "bushes" | "fence" | "mountains";

/**
 * Одна заплатка шва «ветка → схождение J» в ЛОКАЛЬНЫХ координатах J
 * (x — поперёк, z — вдоль; линия входа в J = z 0). Ветка — расходящаяся дуга,
 * её торцевая кромка наклонена к входу J: внешний угол висит ПЕРЕД линией
 * входа (z<0 — дыра), внутренний — заходит внутрь J. Заплата — четырёхугольник
 * между кромкой ветки (обрезанной по ширине J) и линией входа; в геометрии
 * мира это ещё один полигон пола (см. geometry/Footprint).
 */
export interface SeamPatchSpec {
  /** Цвет пола ветки (заплата визуально принадлежит ветке). */
  color: string;
  /** Торец ветки: внешний (обрезан стеной J) и внутренний углы кромки. */
  edgeA: Vec2;
  edgeB: Vec2;
  /** Те же u на линии входа J (z=0). */
  lineA: Vec2;
  lineB: Vec2;
}

/**
 * Шов стыка веток развилки с их схождением J. Заполняется генератором только
 * у J (TrackBuilder.computeSeam, без rng — детерминизм сохранён). Заплатки
 * закрывают клиновидные дыры между торцами расходящихся веток и входом J;
 * стены вокруг них выводит FootprintIndex как границу объединения полов.
 */
export interface SeamSpec {
  patches: SeamPatchSpec[];
}

export interface SectionSpec {
  index: number;
  tier: number; // 1-3 сложность; 0 — служебная секция подхода к башне, без врагов
  /** Цвет пола (задаёт окружение секции, см. world/biomes/biomes.ts → applyBiome). */
  color: string;
  borderStyle: BorderStyle;
  /**
   * Окружение секции — только ВНЕШНИЙ ВИД (пол, стены, декор, во что превращаются
   * кусты/деревья/бордюр), игровая логика от него не зависит. Назначается по школе
   * ворот, через которые входят в секцию (см. world/biomes/biomes.ts).
   */
  biome: BiomeId;
  /** Протяжённость секции вдоль её собственной оси (локальные z: 0..length). */
  length: number;
  /** Ширина коридора секции (первая секция — узкий вход; остальные 3×). */
  width: number;
  /** Мировая точка начала осевой линии секции (локальный (0, 0)). */
  start: Vec2;
  /** Мировая точка конца осевой линии секции (локальный (0, length)). */
  end: Vec2;
  /** Направление коридора в мире В НАЧАЛЕ секции, рад (0 = +Z). */
  yaw: number;
  /**
   * Кривизна оси секции, рад/метр: курс в точке пути s равен `yaw +
   * curvature*s` — секция является дугой ПОСТОЯННОЙ кривизны (0 — прямая, как
   * ветки/схождения развилки и самая первая секция). Соседняя секция всегда
   * начинается с курсом, равным курсу В КОНЦЕ предыдущей
   * (`yaw + curvature*length`), поэтому стык между секциями не даёт видимого
   * излома — поворот размазан по всей длине секции.
   */
  curvature: number;
  /** Выходные ворота на конце секции (см. GateSpec). */
  gates: GateSpec[];
  /**
   * Данные шва «ветки → схождение» в ЛОКАЛЬНЫХ координатах секции-схождения J
   * (u — поперёк, d — вдоль; d<0 — до линии входа в J). Заполняется генератором
   * только у J (см. TrackBuilder.computeSeam); из них geometry/Footprint строит
   * полигоны-заплатки пола. Ветки — расходящиеся дуги, их торцевые кромки НЕ
   * параллельны входу J: без заплаток на стыке клиновидные дыры (внутренние
   * углы кромок висят перед входом J) и «языки» пола за шириной J.
   */
  seam?: SeamSpec | null;
  /** Признак ветки развилки: A/B параллельные коридоры за двойными воротами. */
  forkBranch?: "a" | "b";
  /**
   * Тупиковый рукав: эта ветка развилки никуда не сходится — за ней нет
   * выходных ворот (`gates` пуст), и барьер, ведущий в неё, НЕ односторонний:
   * можно свободно вернуться и уйти через вторую дверь. Обычная секция или
   * «настоящая» (проходная) ветка развилки — всегда false.
   */
  isDeadEnd?: boolean;
  /** Id ворот родительской секции, через которые входят в эту ветку. */
  forkGateId?: string;
  /** Индекс родительской секции (строить ветку, пока игрок у развилки или прошёл ворота). */
  forkParentIndex?: number;
  witches: WitchSpec[];
  bonfires: BonfireSpec[];
  practiceTargets: PracticeTargetSpec[];
  chests: ChestSpec[];
  /** Перпендикулярные боковые тупики-ниши (0..N, обычно 0..1) — см. SideSpurSpec. */
  sideSpurs: SideSpurSpec[];
  grass: ScatterSeed[];
  /**
   * Кусты внутри проходимой ширины коридора (не бордюрные — те стоят у стен и
   * чисто декоративны, см. BorderStyle "bushes"). Это укрытия стелса: игрок
   * внутри куста невидим для ведьм (см. stealth/bushes.ts). Без коллизии —
   * игрок заходит внутрь; редкие и небольшие, не ближе 3 м к сущностям.
   */
  bushes: ScatterSeed[];
  /**
   * Деревья рощ (кучки по 3–5, сиды уже разложены по группам генератором).
   * Перекрывают обзор ведьм — за ними можно скрыться; у стволов есть коллизия.
   * Не ближе 4.5 м к сущностям и кустам.
   */
  trees: ScatterSeed[];
  borderLeft: ScatterSeed[];
  borderRight: ScatterSeed[];
}
