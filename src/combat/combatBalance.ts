/**
 * Баланс боевой системы — все числа в одном месте, чтобы настраивать бой, не
 * лазая по логике. Базовые значения подобраны так, чтобы обычная ведьма падала
 * примерно за три верных удара, а игрок выдерживал три неотражённых — как было
 * в схеме «3 попадания»; усталость заклинаний растягивает бой, если бить одним и
 * тем же.
 */

// ---------- Игрок ----------

/** Максимум Силы игрока. */
export const PLAYER_MAX_POWER = 100;
/** Сколько Силы игрок восстанавливает за секунду вне боя (пустая шкала наполняется ≈ за 7 с). */
export const PLAYER_REGEN_PER_SECOND = 15;

// ---------- Урон ----------

/** Урон верно произнесённого заклинания до мастерства и усталости. */
export const SPELL_BASE_DAMAGE = 30;
/** Прибавка к урону за уровень мастерства (мастерство 0…5 → до +30 %). */
export const MASTERY_DAMAGE_BONUS = 0.06;
/** Сколько Силы отнимает у игрока каждая неотражённая атака ведьмы. */
export const WITCH_HIT_DAMAGE = 34;

// ---------- Усталость заклинаний ----------

/** Сколько последних удачных применений заклинаний помним. */
export const FATIGUE_WINDOW = 8;
/**
 * Сколько применений в окне заклинание бьёт на полную, прежде чем начнёт уставать.
 * При окне 8 и трёх бесплатных применениях четырьмя заклинаниями по кругу можно бить
 * на полную, тремя — почти (−20 %), двумя — заметно слабее, одним — на пределе усталости.
 */
export const FATIGUE_FREE_USES = 3;
/** Потеря урона за каждое применение сверх бесплатных (0.2 = −20 %). */
export const FATIGUE_STEP = 0.2;
/** Ниже этого множителя урон от усталости не падает. */
export const FATIGUE_MIN_MULTIPLIER = 0.25;

// ---------- Силы противников ----------

/** Сила обычной ведьмы. */
export const WITCH_POWER = 90;
