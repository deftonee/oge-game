/**
 * «Подпись» мира: короткая строка, которая меняется при любом изменении описания мира
 * (геометрия, ведьмы, сундуки, декор). Один и тот же seed при одинаковом генераторе даёт одну и ту
 * же подпись; если генератор поменяли, подпись другая — и сохранение понимает, что мир уже не тот.
 *
 * FNV-1a (32 бита) по JSON описания + его длина: для защиты от «устаревшего сохранения» хватает,
 * криптостойкость не нужна. Считается один раз при запуске.
 */
export function worldSignature(world: unknown): string {
  const text = JSON.stringify(world);
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return `${text.length.toString(36)}-${(hash >>> 0).toString(36)}`;
}
